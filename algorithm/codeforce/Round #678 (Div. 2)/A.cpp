#include <cstdio>
int main() {
    int t;
    scanf("%d", &t);
    while (t--) {
        int n;
        int m;
        scanf("%d", &n);
        scanf("%d", &m);
        int sum = 0;
        for (int i = 0; i < n; i++) {
            int num;
            scanf("%d", &num);
            sum += num;
        }
        if (sum == m)
            printf("YES\n");
        else
            printf("NO\n");
    }
    return 0;
}
